#!/usr/bin/env python3
"""Derive the one hydration graph from real Cargo metadata; never compile Cargo code."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tomllib

REPO = Path(__file__).resolve().parents[2]
OUTPUT = REPO / "third-party/rust/hydrate"
sys.path.insert(0, str(REPO / "tools/ui"))
from wasm_bundle import GENERATION_INPUTS


def run(argv, **kwargs):
    return subprocess.check_output(argv, cwd=REPO, text=True, **kwargs)


def value(item):
    if isinstance(item, bool):
        return str(item).lower()
    if isinstance(item, (str, int)):
        return json.dumps(item, ensure_ascii=False)
    if isinstance(item, list):
        return "[" + ", ".join(value(v) for v in item) + "]"
    if isinstance(item, dict):
        return "{ " + ", ".join(json.dumps(k) + " = " + value(v) for k, v in item.items()) + " }"
    raise ValueError("unsupported generated TOML value: " + repr(item))


def lock_identity(package):
    return (package["name"], package["version"], package.get("source"))


def check_lock(canonical, projected):
    originals = {lock_identity(p): p for p in canonical["package"]}
    selected = {lock_identity(p): p for p in projected["package"]}

    def edges(package, packages):
        result = set()
        for label in package.get("dependencies", []):
            words = label.split(" ", 2)
            candidates = [key for key in packages if key[0] == words[0]
                          and (len(words) < 2 or key[1] == words[1])
                          and (len(words) < 3 or key[2] == words[2].strip("()"))]
            if len(candidates) != 1:
                raise ValueError("ambiguous lock dependency identity: " + label)
            result.add(candidates[0])
        return result

    for identity, package in selected.items():
        original = originals.get(identity)
        if original is None or original.get("checksum") != package.get("checksum"):
            raise ValueError("hydration dependency is not in the canonical lock: " + repr(identity))
        if not edges(package, selected).issubset(edges(original, originals)):
            raise ValueError("hydration dependency introduced an unreviewed edge: " + repr(identity))


def root_aliases(ui, metadata, graph):
    resolve = metadata["resolve"]
    roots = [node for node in resolve["nodes"] if node["id"] == resolve["root"]]
    if len(roots) != 1:
        raise ValueError("hydration metadata requires one resolved root")
    aliases = []
    for edge in roots[0]["deps"]:
        declared = [dep for dep in ui["dependencies"]
                    if (dep["rename"] or dep["name"]).replace("-", "_") == edge["name"]]
        packages = [package for package in metadata["packages"] if package["id"] == edge["pkg"]]
        if len(declared) != 1 or len(packages) != 1 or declared[0]["name"] != packages[0]["name"]:
            raise ValueError("missing or ambiguous active hydration dependency: " + repr(edge))
        name = declared[0]["rename"] or declared[0]["name"]
        if graph.count('alias(\n    name = ' + value(name) + ',') != 1:
            raise ValueError("missing or ambiguous active hydration alias: " + name)
        aliases.append("//third-party/rust/hydrate:" + name)
    if len(set(aliases)) != len(aliases):
        raise ValueError("duplicate active hydration dependency")
    return sorted(aliases)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reindeer", required=True, help="authenticated repository-pinned Reindeer executable")
    args = parser.parse_args()
    channel = tomllib.loads((REPO / "rust-toolchain.toml").read_text())["toolchain"]["channel"]
    cargo = run(["rustup", "which", "--toolchain", channel, "cargo"]).strip()
    rustc = run(["rustup", "which", "--toolchain", channel, "rustc"]).strip()
    metadata = json.loads(run([cargo, "metadata", "--offline", "--locked", "--no-deps",
                               "--format-version", "1", "--manifest-path", "backend/Cargo.toml"]))
    ui = next(p for p in metadata["packages"] if p["name"] == "console-payroll-ui")
    workspace = tomllib.loads((REPO / "backend/Cargo.toml").read_text())
    if len(ui["targets"]) != 1 or Path(ui["targets"][0]["src_path"]) != REPO / "backend/crates/payroll/ui/src/lib.rs":
        raise ValueError("hydration projection requires the real single UI library")
    for dep in ui["dependencies"]:
        if (dep["kind"] is not None or dep["target"] is not None or dep.get("path")
                or dep["source"] != "registry+https://github.com/rust-lang/crates.io-index"
                or dep["registry"] is not None):
            raise ValueError("unsupported UI dependency kind/source: " + repr(dep))
    OUTPUT.mkdir(parents=True, exist_ok=True)
    lines = ["# @generated by tools/buck/gen_hydrate.py; canonical manifests remain authoritative.",
             "[workspace]", "resolver = " + value(workspace["workspace"]["resolver"]), "", "[package]"]
    for key in ("name", "version", "description", "license", "edition", "rust_version"):
        if ui[key] is not None:
            lines.append(key.replace("_", "-") + " = " + value(ui[key]))
    lines += ["publish = false", "autobins = false", "autoexamples = false", "autotests = false",
              "autobenches = false", "", "[lib]", "name = " + value(ui["targets"][0]["name"]),
              "path = " + value(os.path.relpath(ui["targets"][0]["src_path"], OUTPUT)),
              "crate-type = " + value(ui["targets"][0]["crate_types"]), "", "[features]"]
    lines += [json.dumps(k) + " = " + value(v) for k, v in sorted(ui["features"].items())]
    lines += ["", "[dependencies]"]
    for dep in sorted(ui["dependencies"], key=lambda d: d["rename"] or d["name"]):
        spec = {"version": dep["req"], "default-features": dep["uses_default_features"],
                "optional": dep["optional"], "features": dep["features"]}
        if dep["rename"]:
            spec["package"] = dep["name"]
        lines.append(json.dumps(dep["rename"] or dep["name"]) + " = " + value(spec))
    for registry, patches in workspace.get("patch", {}).items():
        lines += ["", "[patch." + json.dumps(registry) + "]"]
        for name, original in sorted(patches.items()):
            spec = dict(original)
            if "path" in spec:
                path = (REPO / "backend" / spec["path"]).resolve()
                if not path.is_relative_to(REPO / "third-party/rust"):
                    raise ValueError("patched package escapes canonical third-party root")
                spec["path"] = os.path.relpath(path, OUTPUT)
            lines.append(json.dumps(name) + " = " + value(spec))
    (OUTPUT / "Cargo.toml").write_text("\n".join(lines) + "\n")
    canonical_bytes = (REPO / "backend/Cargo.lock").read_bytes()
    (OUTPUT / "Cargo.lock").write_bytes(canonical_bytes)
    metadata_command = [cargo, "metadata", "--offline", "--format-version", "1",
                        "--manifest-path", str(OUTPUT / "Cargo.toml")]
    # Cargo prunes the private lock. Verify exact identities/checksums/edges
    # against the canonical lock before permitting locked Reindeer discovery.
    run(metadata_command + ["--no-default-features", "--features", "hydrate,islands"])
    check_lock(tomllib.loads(canonical_bytes.decode()), tomllib.loads((OUTPUT / "Cargo.lock").read_text()))
    active = json.loads(run(metadata_command + ["--locked", "--no-default-features", "--features",
                                               "hydrate,islands", "--filter-platform", "wasm32-unknown-unknown"]))
    discovery = json.loads(run(metadata_command + ["--locked", "--all-features"]))
    if (REPO / "backend/Cargo.lock").read_bytes() != canonical_bytes:
        raise ValueError("canonical lock changed during hydration generation")
    config = tomllib.loads((REPO / "third-party/rust/reindeer.toml").read_text())
    config.update(include_top_level=False, include_workspace_members=False,
                  include_workspace_dev_dependencies=False)
    config["buck"]["buckfile_imports"] += '''
[
    export_file(
        name = "hydration-" + source,
        src = source,
        mode = "reference",
        visibility = ["PUBLIC"],
    )
    for source in ["BUCK", "Cargo.toml", "Cargo.lock", "root-dependencies.json", "input-lock.json"]
]
'''
    config["platform"] = {
        "wasm32": {"target": "wasm32-unknown-unknown", "execution-platform": False,
                   "features": ["hydrate", "islands"]},
        "macos-arm64": {"target": "aarch64-apple-darwin", "execution-platform": True, "features": []},
        "linux-arm64": {"target": "aarch64-unknown-linux-gnu", "execution-platform": True, "features": []},
        "linux-x86_64": {"target": "x86_64-unknown-linux-gnu", "execution-platform": True, "features": []},
    }
    config_lines = ["# @generated from canonical Reindeer configuration and the fixed hydrate platform."]
    for key, item in config.items():
        if not isinstance(item, dict):
            config_lines.append(key + " = " + value(item))
    config_lines += ["", "[buck]"] + [k + " = " + value(v) for k, v in config["buck"].items()]
    for name, platform in config["platform"].items():
        config_lines += ["", "[platform." + name + "]"] + [k + " = " + value(v) for k, v in platform.items()]
    (OUTPUT / "reindeer.toml").write_text("\n".join(config_lines) + "\n")
    fixups = OUTPUT / "fixups"
    if fixups.exists():
        shutil.rmtree(fixups)
    fixup_hashes = {}
    for package in discovery["packages"]:
        if package.get("source") is None and package["name"] != ui["name"]:
            raise ValueError("active local hydration dependency needs reviewed namespace handling")
        source = REPO / "third-party/rust/fixups" / package["name"]
        if not source.is_dir():
            continue
        for path in sorted(source.rglob("*")):
            if path.is_file():
                if path.name != "fixups.toml" or any(token in path.read_text() for token in ("//", "extra_srcs", "overlay", "extra_deps")):
                    raise ValueError("path-bearing hydration fixup needs reviewed projection: " + str(path))
                target = fixups / path.relative_to(source.parent)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(path, target)
                fixup_hashes[path.relative_to(REPO).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    run([args.reindeer, "--cargo-path", cargo, "--rustc-path", rustc,
         "--cargo-options=--offline", "--cargo-options=--locked", "--third-party-dir", str(OUTPUT),
         "--manifest-path", str(OUTPUT / "Cargo.toml"), "buckify"])
    graph = (OUTPUT / "BUCK").read_text()
    if "//third-party/rust:" in graph:
        raise ValueError("hydration graph leaked server namespace")
    (OUTPUT / "root-dependencies.json").write_text(json.dumps(root_aliases(ui, active, graph), indent=2) + "\n")
    (OUTPUT / "input-lock.json").write_text(json.dumps({
        "inputs": {path: hashlib.sha256((REPO / path).read_bytes()).hexdigest()
                   for path in sorted(set(GENERATION_INPUTS) | {
                       path.relative_to(REPO).as_posix()
                       for path in (REPO / "third-party/rust/fixups").rglob("*") if path.is_file()})},
        "canonical_lock_sha256": hashlib.sha256(canonical_bytes).hexdigest(),
        "fixups": fixup_hashes,
        "rust_channel": channel,
    }, indent=2, sort_keys=True) + "\n")
    print("Generated isolated hydration metadata and Buck graph without Cargo compilation")


if __name__ == "__main__":
    main()
